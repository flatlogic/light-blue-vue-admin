import { test, expect } from '@playwright/test'

test('preserves login, dashboard map/calendar/charts, Bootstrap controls, notifications and logout', async ({ page }) => {
  const errors = [], localErrors = [], messages = []
  page.on('pageerror', e => { errors.push(e.message); console.log('PAGE ERROR:', e.message) })
  page.on('console', m => { if (['warning','error'].includes(m.type())) { messages.push(m.text()); console.log('CONSOLE', m.type(), m.text()) } })
  page.on('response', r => { if (r.url().startsWith('http://127.0.0.1:4413/') && r.status() >= 400) localErrors.push(r.url()) })
  await page.route(/googletagmanager\.com|yandex-metrica-watch/, route => route.fulfill({ body: '', contentType: 'application/javascript' }))
  await page.addInitScript(() => localStorage.setItem('authenticated', 'false'))
  await page.goto('./')

  await expect(page).toHaveURL(/#\/login$/)
  await page.getByLabel('Email', { exact: true }).fill('demo@example.com')
  await page.getByLabel('Password', { exact: true }).fill('demo')
  await page.getByRole('button', { name: /Login$/ }).click()
  await expect(page).toHaveURL(/#\/app\/dashboard$/)
  await expect(page.locator('.page-title')).toContainText('Dashboard')
  await expect(page.locator('.map svg').first()).toBeVisible()
  await expect(page.locator('.lb-calendar .vc-container')).toBeVisible()
  await expect(page.locator('canvas.area-chart')).toBeVisible()
  await page.locator('.lb-calendar .vc-day').filter({ has: page.locator('.vc-dot') }).first().hover()
  await expect(page.getByText('The flower bed', { exact: true })).toBeVisible()
  await expect(page.locator('.vc-popover-content')).not.toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.locator('.page-title').hover()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect(page.locator('.visits-page')).toContainText('75%')
  await page.screenshot({ path: 'test-results/dashboard.png', fullPage: false })

  await page.locator('.avatar-toggle .dropdown-toggle').click()
  await expect(page.getByText('You have 13 notifications')).toBeVisible()
  await page.locator('.avatar-toggle .dropdown-toggle').click()
  await page.locator('.sidebar').getByRole('link', { name: 'Tables Basic' }).click()
  await expect(page.locator('.tables-basic tbody').first().locator('tr')).toHaveCount(5)
  const image = page.locator('.tables-basic tbody img').first()
  await expect(image).toBeVisible()
  expect(await image.evaluate(el => el.naturalWidth)).toBeGreaterThan(0)

  await page.locator('.sidebar').getByRole('link', { name: 'Notifications', exact: true }).click()
  await page.getByRole('button', { name: 'Info Message' }).click()
  await expect(page.locator('.toasted.info')).toContainText('Launching thermonuclear war...')
  await expect(page.locator('.toasted.info')).toHaveCSS('opacity', '1')
  await page.getByText('Cancel launch', { exact: true }).click()
  await expect(page.locator('.toasted.info')).toContainText('Thermonuclear war averted')
  await page.locator('.location-selector .bottom.left').click()
  await page.getByRole('button', { name: 'Success Message' }).click()
  await expect(page.locator('.toasted-container.bottom-left')).toContainText('Showing success message was successful!')

  await page.locator('.sidebar').getByRole('link', { name: 'Components', exact: true }).click()
  await page.locator('.sidebar').getByRole('link', { name: 'Charts', exact: true }).click()
  await expect(page.locator('.apexcharts-canvas').first()).toBeVisible()
  await expect(page.locator('.highcharts-container')).toHaveCount(2)
  await expect(page.locator('.charts-overview canvas')).toHaveCount(3)
  const widget = page.locator('.charts-overview .widget').first()
  await widget.locator('a[id^="collapseId"]').click()
  await expect(widget.locator('.widget-body')).not.toBeVisible()
  await widget.locator('a[id^="expandId"]').click()
  await expect(widget.locator('.widget-body')).toBeVisible()
  await page.locator('.sidebar').getByRole('link', { name: 'Icons', exact: true }).click()
  await expect(page.getByRole('tab').first()).toBeVisible()
  await page.getByRole('tab').last().click()
  await expect(page.locator('.tab-pane.active .fa').first()).toBeVisible()
  await page.locator('.app-header .flaticon-power-1').click()
  await expect(page).toHaveURL(/#\/login$/)
  expect(errors).toEqual([])
  expect(localErrors).toEqual([])
  expect(messages).toEqual([])
})


test('mobile Bootstrap sidebar opens and closes after login', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route(/googletagmanager\.com|yandex-metrica-watch/, route => route.fulfill({ body: '', contentType: 'application/javascript' }))
  await page.goto('./#/login')
  await page.getByLabel('Email', { exact: true }).fill('demo@example.com')
  await page.getByLabel('Password', { exact: true }).fill('demo')
  await page.getByRole('button', { name: /Login$/ }).click()
  await expect(page).toHaveURL(/#\/app\/dashboard$/)
  const toggle = page.locator('.app-header .la-navicon')
  await toggle.click()
  await expect(page.locator('.sidebar').getByRole('link', { name: 'Typography', exact: true })).toBeInViewport()
  await page.locator('.sidebar').getByRole('link', { name: 'Typography', exact: true }).click()
  await toggle.click()
  await expect(page.locator('.sidebar')).not.toBeInViewport()
  await expect(page.locator('.page-title')).toContainText('Typography')
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: false })
  expect(errors).toEqual([])
})
